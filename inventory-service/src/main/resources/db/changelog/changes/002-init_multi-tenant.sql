CREATE OR REPLACE FUNCTION enforce_products_brand_tenant_consistency()
    RETURNS TRIGGER AS $$
DECLARE
    b_tenant BIGINT;
BEGIN
    SELECT tenant_id INTO b_tenant FROM brands WHERE brand_id = NEW.brand_id;
    IF b_tenant IS NULL THEN
        RAISE EXCEPTION 'Brand % not found or has no tenant', NEW.brand_id;
    END IF;
    IF NEW.tenant_id IS DISTINCT FROM b_tenant THEN
        RAISE EXCEPTION 'Tenant mismatch: products.tenant_id(%) <> brands.tenant_id(%) for brand_id=%',
            NEW.tenant_id, b_tenant, NEW.brand_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_products_brand_tenant_check ON products;
CREATE TRIGGER trg_products_brand_tenant_check
    BEFORE INSERT OR UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION enforce_products_brand_tenant_consistency();

CREATE OR REPLACE FUNCTION enforce_item_products_tenant_consistency()
    RETURNS TRIGGER AS $$
DECLARE
    i_tenant BIGINT;
    p_tenant BIGINT;
BEGIN
    SELECT tenant_id INTO i_tenant FROM items WHERE item_id = NEW.item_id;
    IF i_tenant IS NULL THEN
        RAISE EXCEPTION 'Item % not found or has no tenant', NEW.item_id;
    END IF;
    SELECT tenant_id INTO p_tenant FROM products WHERE product_id = NEW.product_id;
    IF p_tenant IS NULL THEN
        RAISE EXCEPTION 'Product % not found or has no tenant', NEW.product_id;
    END IF;
    IF NEW.tenant_id IS DISTINCT FROM i_tenant OR NEW.tenant_id IS DISTINCT FROM p_tenant THEN
        RAISE EXCEPTION 'Tenant mismatch in item_products: item_products.tenant_id(%) vs items(%) vs products(%)',
            NEW.tenant_id, i_tenant, p_tenant;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_item_products_tenant_check ON item_products;
CREATE TRIGGER trg_item_products_tenant_check
    BEFORE INSERT OR UPDATE ON item_products
    FOR EACH ROW EXECUTE FUNCTION enforce_item_products_tenant_consistency();

