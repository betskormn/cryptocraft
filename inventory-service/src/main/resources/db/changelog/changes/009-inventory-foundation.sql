--changeset roman:009-stock-consumptions splitStatements:true endDelimiter:;
--comment: recipe write-offs per order; one row per (venue, order) makes repeated calls idempotent
CREATE TABLE stock_consumptions
(
    consumption_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT      NOT NULL REFERENCES tenants (tenant_id),
    order_id       VARCHAR(64) NOT NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP            DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_stock_consumptions_tenant_order UNIQUE (tenant_id, order_id)
);

-- requested: what the recipes needed; consumed: what was actually taken (stock never goes below zero)
CREATE TABLE stock_consumption_lines
(
    line_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumption_id BIGINT         NOT NULL REFERENCES stock_consumptions (consumption_id) ON DELETE CASCADE,
    product_id     BIGINT         REFERENCES products (product_id) ON DELETE SET NULL,
    product_name   VARCHAR(255)   NOT NULL,
    requested      NUMERIC(12, 3) NOT NULL,
    consumed       NUMERIC(12, 3) NOT NULL,
    tenant_id      BIGINT         NOT NULL REFERENCES tenants (tenant_id)
);

CREATE INDEX ix_stock_consumption_lines_consumption ON stock_consumption_lines (consumption_id);

