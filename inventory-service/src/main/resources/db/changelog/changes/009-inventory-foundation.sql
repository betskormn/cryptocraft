--changeset roman:009-internal-item-prices-fn splitStatements:false
CREATE FUNCTION internal_item_prices()
    RETURNS TABLE
            (
                item_id            BIGINT,
                tenant_id          BIGINT,
                tenant_slug        VARCHAR,
                price_tick_seconds INT,
                name               VARCHAR,
                type               SMALLINT,
                display_order      INT,
                stopped            BOOLEAN,
                base_price         NUMERIC,
                min_price          NUMERIC,
                max_price          NUMERIC
            )
    LANGUAGE sql
    STABLE
    SECURITY DEFINER
    SET search_path = public
AS $$
    SELECT i.item_id, i.tenant_id, t.slug, t.price_tick_seconds, i.name, i.type, i.display_order, i.stopped,
           i.base_price, i.min_price, i.max_price
    FROM items i
             JOIN tenants t ON t.tenant_id = i.tenant_id
    WHERE t.status = 1
$$;

