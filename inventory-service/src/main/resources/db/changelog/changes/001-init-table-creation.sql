-- =========================================
-- INITIAL DATABASE SCHEMA (POSTGRESQL)
-- =========================================

-- =========================================
-- BRANDS
-- =========================================
CREATE TABLE brands
(
    brand_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_brands_name UNIQUE (name)
);

-- =========================================
-- ITEMS
-- =========================================
CREATE TABLE items
(
    item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    recipe     VARCHAR(255),
    image      VARCHAR(255),
    type       SMALLINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =========================================
-- PRODUCTS
-- =========================================
CREATE TABLE products
(
    product_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL,
    description       TEXT,
    image             VARCHAR(255),
    quantity_in_stock INT NOT NULL,
    unit              SMALLINT NOT NULL,
    brand_id          BIGINT NOT NULL,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_brand
        FOREIGN KEY (brand_id)
            REFERENCES brands (brand_id)
);

-- Index for querying products by brand
CREATE INDEX ix_products_brand_id ON products (brand_id);

-- =========================================
-- ITEM_PRODUCTS (JOIN TABLE)
-- =========================================
CREATE TABLE item_products
(
    item_id    BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity   INT NOT NULL DEFAULT 1,

    -- Composite key – matches @EmbeddedId
    CONSTRAINT pk_item_products PRIMARY KEY (item_id, product_id),

    CONSTRAINT fk_item_products_item
        FOREIGN KEY (item_id)
            REFERENCES items(item_id)
            ON DELETE CASCADE,

    CONSTRAINT fk_item_products_product
        FOREIGN KEY (product_id)
            REFERENCES products(product_id)
            ON DELETE CASCADE
);

-- PK(item_id, product_id) already creates index on (item_id, product_id).
-- Needed index for reverse queries: "all items using product"
CREATE INDEX ix_item_products_product_id ON item_products (product_id);