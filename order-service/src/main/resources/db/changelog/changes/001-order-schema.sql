--changeset roman:001-order-pending-stock-fn splitStatements:false
--comment: orders whose recipe write-off has not reached Inventory yet, across venues, for the retry job
CREATE OR REPLACE FUNCTION pending_stock_write_offs(p_older_than_seconds INT)
    RETURNS TABLE
            (
                order_id  UUID,
                tenant_id BIGINT
            )
    LANGUAGE sql
    STABLE
    SECURITY DEFINER
    SET search_path = public
AS $$
    SELECT o.order_id, o.tenant_id
    FROM orders o
    WHERE o.stock_status = 1
      AND o.created_at < (now() AT TIME ZONE 'UTC') - make_interval(secs => p_older_than_seconds)
    ORDER BY o.created_at
    LIMIT 100
$$;

