--changeset roman:001-order-current-tenant-fn splitStatements:false
--comment: NULL when app.tenant_id is unset or empty, so policies fail closed (set by tenant-support)
CREATE OR REPLACE FUNCTION app_current_tenant()
    RETURNS BIGINT
    LANGUAGE sql
    STABLE
AS $$
    SELECT NULLIF(current_setting('app.tenant_id', true), '')::bigint
$$;

--changeset roman:001-order-tables splitStatements:true endDelimiter:;
--comment: tables with a QR code, visits (table sessions), guests of a visit, and orders sent to the kitchen/bar

-- a venue's table; code is the random token printed in its QR code
CREATE TABLE venue_tables
(
    table_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL,
    label      VARCHAR(50) NOT NULL,
    code       VARCHAR(32) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP            DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_venue_tables_tenant_label UNIQUE (tenant_id, label),
    CONSTRAINT uk_venue_tables_code UNIQUE (code)
);

-- status: 1 OPEN, 2 CLOSED (SessionStatus)
CREATE TABLE table_sessions
(
    session_id UUID PRIMARY KEY,
    tenant_id  BIGINT    NOT NULL,
    table_id   BIGINT    NOT NULL REFERENCES venue_tables (table_id),
    status     SMALLINT  NOT NULL,
    closed_at  TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP          DEFAULT CURRENT_TIMESTAMP
);

-- at most one open visit per table
CREATE UNIQUE INDEX ux_table_sessions_open_table ON table_sessions (table_id) WHERE status = 1;
CREATE INDEX ix_table_sessions_tenant_status ON table_sessions (tenant_id, status);

-- participant_id doubles as the guest's anonymous token until Identity Service exists
CREATE TABLE session_participants
(
    participant_id UUID PRIMARY KEY,
    tenant_id      BIGINT      NOT NULL,
    session_id     UUID        NOT NULL REFERENCES table_sessions (session_id),
    display_name   VARCHAR(50),
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP            DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_session_participants_session ON session_participants (session_id);

-- status: 1 PLACED, 2 CANCELLED (OrderStatus); stock_status: 1 PENDING, 2 WRITTEN_OFF (StockStatus)
-- client_order_id: the client's idempotency key, a resent order is not placed twice
CREATE TABLE orders
(
    order_id        UUID PRIMARY KEY,
    tenant_id       BIGINT         NOT NULL,
    session_id      UUID           NOT NULL REFERENCES table_sessions (session_id),
    participant_id  UUID           NOT NULL REFERENCES session_participants (participant_id),
    client_order_id VARCHAR(64)    NOT NULL,
    status          SMALLINT       NOT NULL,
    stock_status    SMALLINT       NOT NULL,
    total           NUMERIC(12, 2) NOT NULL,
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP               DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_orders_tenant_client_order UNIQUE (tenant_id, client_order_id)
);

CREATE INDEX ix_orders_session ON orders (session_id);
CREATE INDEX ix_orders_participant ON orders (participant_id);
CREATE INDEX ix_orders_stock_pending ON orders (stock_status) WHERE stock_status = 1;

-- the price is locked when the order is sent: unit_price never changes afterwards
-- item_type: 1 MEAL, 2 DRINK (ItemType), as in Inventory
CREATE TABLE order_lines
(
    line_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   UUID           NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    tenant_id  BIGINT         NOT NULL,
    item_id    BIGINT         NOT NULL,
    item_name  VARCHAR(255)   NOT NULL,
    item_type  SMALLINT       NOT NULL,
    quantity   INT            NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(12, 2) NOT NULL
);

CREATE INDEX ix_order_lines_order ON order_lines (order_id);

